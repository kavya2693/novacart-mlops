"""NovaCart synthetic data engine (Project 0).

Simulates a mid-size e-commerce retailer. Produces five tables:
customers, products, orders, order_items, events. Everything is driven by a
single seeded RNG so the whole company is reproducible.

Design goals (from the architecture pressure-test):
- The 30-day forward churn outcome is a STOCHASTIC renewal event, not a
  deterministic function of the backward features. So a model recovers a
  *noisy* signal (realistic ROC-AUC ~0.80s), not its own generator.
- Every order carries a real timestamp so features can be computed strictly
  point-in-time and the label strictly forward.
"""
from __future__ import annotations

from datetime import date, timedelta

import numpy as np
import pandas as pd

from novacart.common.config import CATEGORIES, settings
from novacart.common import storage
from novacart.common.dates import as_date as _to_date, opt_date as _opt_date

SEGMENTS = ["bargain", "regular", "vip"]
SEGMENT_WEIGHTS = [0.45, 0.40, 0.15]
# Base monthly order rate (orders per 30 days) and average basket size by segment.
SEGMENT_RATE = {"bargain": 0.6, "regular": 1.1, "vip": 2.4}
SEGMENT_AOV = {"bargain": 22.0, "regular": 55.0, "vip": 140.0}

def generate_products(rng: np.random.Generator, n: int = 300) -> pd.DataFrame:
    cats = rng.choice(CATEGORIES, size=n)
    # Log-normal prices, floored, rounded to cents.
    prices = np.round(np.exp(rng.normal(3.1, 0.7, size=n)) + 3.0, 2)
    return pd.DataFrame(
        {"product_id": np.arange(1, n + 1), "category": cats, "price": prices}
    )


def generate_customers(rng: np.random.Generator, n: int, ref: date) -> pd.DataFrame:
    segments = rng.choice(SEGMENTS, size=n, p=SEGMENT_WEIGHTS)
    # Signup between 40 and 720 days before the reference date.
    signup_offsets = rng.integers(40, 720, size=n)
    signup_dates = [ref - timedelta(days=int(o)) for o in signup_offsets]
    # Latent engagement in [0,1]; VIPs skew high, bargain skews low.
    seg_center = {"bargain": 0.35, "regular": 0.55, "vip": 0.75}
    engagement = np.clip(
        [rng.normal(seg_center[s], 0.18) for s in segments], 0.03, 0.99
    )
    # A subset "go dormant" at some point (onset day offset before ref, or None).
    dormant = rng.random(n) < (0.45 * (1 - engagement))  # low engagement -> more dormancy
    dormancy_onset = []
    for i in range(n):
        if dormant[i]:
            max_back = min(signup_offsets[i] - 1, 200)
            onset = ref - timedelta(days=int(rng.integers(1, max(2, max_back))))
            dormancy_onset.append(onset)
        else:
            dormancy_onset.append(None)
    home_cat = rng.choice(CATEGORIES, size=n)
    return pd.DataFrame(
        {
            "customer_id": np.arange(1, n + 1),
            "segment": segments,
            "signup_date": [d.isoformat() for d in signup_dates],
            "home_category": home_cat,
            "engagement": np.round(engagement, 4),
            "dormancy_onset": [d.isoformat() if d else None for d in dormancy_onset],
        }
    )


def _simulate_orders_for_customer(
    rng: np.random.Generator,
    cust: pd.Series,
    products: pd.DataFrame,
    ref: date,
    horizon: int,
) -> list[dict]:
    """Renewal-process order stream from signup to ref+horizon.

    Rate drops sharply after a dormancy onset. The forward window (ref, ref+h]
    is generated by the *same* process, so whether a purchase lands there is
    genuinely stochastic given the past.
    """
    seg = cust["segment"]
    base_rate = SEGMENT_RATE[seg] * (0.4 + 1.2 * cust["engagement"])  # orders / 30d
    signup = _to_date(cust["signup_date"])
    onset = _opt_date(cust["dormancy_onset"])
    end = ref + timedelta(days=horizon)

    orders = []
    t = signup
    while True:
        active_rate = base_rate
        if onset is not None and t >= onset:
            active_rate *= 0.12  # dormant: rate collapses but not to zero
        daily_rate = max(active_rate, 0.01) / 30.0
        gap = rng.exponential(1.0 / daily_rate)
        t = t + timedelta(days=float(gap))
        if t > end:
            break
        # Basket: 1-4 items, prices from products, VIP buys pricier.
        n_items = int(rng.integers(1, 5))
        prod_sample = products.sample(n_items, random_state=int(rng.integers(0, 1_000_000)))
        discounted = rng.random() < (0.55 if seg == "bargain" else 0.25)
        discount_mult = 0.8 if discounted else 1.0
        orders.append(
            {
                "customer_id": int(cust["customer_id"]),
                "order_ts": t.isoformat(),
                "items": prod_sample,
                "discounted": int(discounted),
                "discount_mult": discount_mult,
            }
        )
    return orders


def generate(seed: int | None = None, n_customers: int | None = None) -> dict[str, pd.DataFrame]:
    """Generate the full company and persist it to the DB. Returns the tables."""
    settings.ensure_dirs()
    rng = np.random.default_rng(seed if seed is not None else settings.seed)
    ref = _to_date(settings.reference_date)
    horizon = settings.churn_horizon_days
    n = n_customers or settings.n_customers

    products = generate_products(rng)
    customers = generate_customers(rng, n, ref)

    order_rows, item_rows = [], []
    order_id = 1
    for _, cust in customers.iterrows():
        cust_orders = _simulate_orders_for_customer(rng, cust, products, ref, horizon)
        for o in cust_orders:
            items = o["items"]
            gross = float((items["price"] * o["discount_mult"]).sum())
            order_rows.append(
                {
                    "order_id": order_id,
                    "customer_id": o["customer_id"],
                    "order_ts": o["order_ts"],
                    "n_items": len(items),
                    "order_total": round(gross, 2),
                    "discounted": o["discounted"],
                }
            )
            for _, it in items.iterrows():
                item_rows.append(
                    {
                        "order_id": order_id,
                        "product_id": int(it["product_id"]),
                        "category": it["category"],
                        "unit_price": round(float(it["price"] * o["discount_mult"]), 2),
                    }
                )
            order_id += 1

    orders = pd.DataFrame(order_rows)
    order_items = pd.DataFrame(item_rows)
    events = _generate_events(rng, customers, ref)

    # Persist (customers table strips the latent columns a real warehouse wouldn't have,
    # but we keep them in a separate _truth table for auditing / the model card).
    truth = customers[["customer_id", "engagement", "dormancy_onset"]].copy()
    customers_public = customers.drop(columns=["engagement", "dormancy_onset"])

    storage.write_df("customers", customers_public)
    storage.write_df("products", products)
    storage.write_df("orders", orders)
    storage.write_df("order_items", order_items)
    storage.write_df("events", events)
    storage.write_df("_customer_truth", truth)

    return {
        "customers": customers_public,
        "products": products,
        "orders": orders,
        "order_items": order_items,
        "events": events,
    }


def _generate_events(rng, customers: pd.DataFrame, ref: date) -> pd.DataFrame:
    """Web sessions + support tickets in the trailing 90 days, correlated w/ state."""
    rows = []
    for _, c in customers.iterrows():
        onset = _opt_date(c["dormancy_onset"])
        recent_active = onset is None or onset > ref - timedelta(days=30)
        eng = c["engagement"]
        n_sessions = int(rng.poisson(max(0.2, eng * 12 * (1.0 if recent_active else 0.2))))
        n_tickets = int(rng.poisson(0.4 + (1 - eng) * 1.5))
        for _ in range(n_sessions):
            day = int(rng.integers(0, 30))
            rows.append(
                {
                    "customer_id": int(c["customer_id"]),
                    "event_type": "session",
                    "event_ts": (ref - timedelta(days=day)).isoformat(),
                }
            )
        for _ in range(n_tickets):
            day = int(rng.integers(0, 90))
            rows.append(
                {
                    "customer_id": int(c["customer_id"]),
                    "event_type": "support_ticket",
                    "event_ts": (ref - timedelta(days=day)).isoformat(),
                }
            )
    return pd.DataFrame(rows)


if __name__ == "__main__":
    tables = generate()
    print("NovaCart data engine — generated & persisted:")
    for name, df in tables.items():
        print(f"  {name:12s} rows={len(df):>7,}")
